export function createCrowdPicker(random=Math.random){
 const bags=new Map(),last=new Map();
 return kind=>{const key=CROWD_LINES[kind]?kind:'good';let bag=bags.get(key);
 if(!bag?.length){bag=[...CROWD_LINES[key]];for(let i=bag.length-1;i>0;i--){const j=Math.floor(random()*(i+1));[bag[i],bag[j]]=[bag[j],bag[i]];}if(bag.at(-1)===last.get(key)){[bag[0],bag[bag.length-1]]=[bag.at(-1),bag[0]];}bags.set(key,bag);}
 const words=bag.pop();last.set(key,words);return words;};
}

