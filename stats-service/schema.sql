CREATE TABLE IF NOT EXISTS daily (day TEXT PRIMARY KEY, uv INTEGER NOT NULL DEFAULT 0, pv INTEGER NOT NULL DEFAULT 0);
CREATE TABLE IF NOT EXISTS visitors (day TEXT NOT NULL, visitor TEXT NOT NULL, PRIMARY KEY(day,visitor));
CREATE TABLE IF NOT EXISTS events (day TEXT NOT NULL, event TEXT NOT NULL, PRIMARY KEY(day,event));
CREATE TRIGGER IF NOT EXISTS visitor_added AFTER INSERT ON visitors BEGIN
 INSERT INTO daily(day,uv,pv) VALUES(NEW.day,1,0) ON CONFLICT(day) DO UPDATE SET uv=uv+1;
END;
CREATE TRIGGER IF NOT EXISTS event_added AFTER INSERT ON events BEGIN
 INSERT INTO daily(day,uv,pv) VALUES(NEW.day,0,1) ON CONFLICT(day) DO UPDATE SET pv=pv+1;
END;
CREATE TABLE IF NOT EXISTS all_visitors (visitor TEXT PRIMARY KEY);
CREATE TABLE IF NOT EXISTS totals (id INTEGER PRIMARY KEY CHECK(id=1),uv INTEGER NOT NULL DEFAULT 0,pv INTEGER NOT NULL DEFAULT 0);
INSERT OR IGNORE INTO totals(id) VALUES(1);
CREATE TRIGGER IF NOT EXISTS all_visitor_added AFTER INSERT ON all_visitors BEGIN
 UPDATE totals SET uv=uv+1 WHERE id=1;
END;
CREATE TRIGGER IF NOT EXISTS total_event_added AFTER INSERT ON events BEGIN
 UPDATE totals SET pv=pv+1 WHERE id=1;
END;
